"""
Module 7: Evidence Bundle
Module: src.ui.pages.p05_evidence
Displays immutable cryptographic forensic evidence bundle for the active selected event.
"""

import json
from dataclasses import asdict
from typing import Dict, Any, List
import streamlit as st

from src.ui.utils.formatting import safe_float, safe_int, safe_str


def render_evidence_page(data_service, selected_event_id: str):
    """
    Render Evidence Bundle module matching Screenshot 7 specification.
    """
    st.markdown(f"<div class='section-header'>FORENSIC EVIDENCE BUNDLE: {selected_event_id}</div>", unsafe_allow_html=True)
    st.markdown(
        """
    <div class="soc-callout">
        <strong>IMMUTABLE FORENSIC CONTAINER:</strong> Cryptographically sealed record generated by Phase 5 Evidence Fusion Engine.
        Captures raw NMEA telemetry, 10-D security features, detector confidence scores, and hardware clock bias.
    </div>
    """,
        unsafe_allow_html=True,
    )

    bundle = data_service.load_event(selected_event_id)
    if not bundle:
        st.error(f"Failed to load evidence bundle for '{selected_event_id}'. Verify backend repository.")
        return

    loc = bundle.location if isinstance(bundle.location, dict) else {}
    lat = safe_float(loc.get("latitude", 0.0))
    lon = safe_float(loc.get("longitude", 0.0))
    alt = safe_float(loc.get("altitude_m", 0.0))
    ts_utc = safe_str(bundle.timestamp_utc or bundle.timestamp_pc, "N/A")
    sess_id = safe_int(bundle.session_id, 0)
    ep_id = safe_int(bundle.epoch_id, 0)

    # 4 Metadata Cards
    c1, c2, c3, c4 = st.columns(4)

    with c1:
        st.markdown(
            f"""
        <div class="kpi-card">
            <div class="kpi-label">EVENT REFERENCE</div>
            <div class="kpi-val" style="font-size: 16px;">{bundle.event_id}</div>
            <div class="kpi-note">SES-{sess_id} / EP-{ep_id}</div>
        </div>
        """,
            unsafe_allow_html=True,
        )

    with c2:
        st.markdown(
            f"""
        <div class="kpi-card">
            <div class="kpi-label">ATOMIC UTC TIMESTAMP</div>
            <div class="kpi-val" style="font-size: 13px;">{ts_utc}</div>
            <div class="kpi-note">GPS Clock Synchronized</div>
        </div>
        """,
            unsafe_allow_html=True,
        )

    with c3:
        st.markdown(
            f"""
        <div class="kpi-card">
            <div class="kpi-label">LOCATION</div>
            <div class="kpi-val" style="font-size: 13px;">{lat:.6f}°, {lon:.6f}°</div>
            <div class="kpi-note">ALT: {alt:.2f} m</div>
        </div>
        """,
            unsafe_allow_html=True,
        )

    with c4:
        st.markdown(
            f"""
        <div class="kpi-card">
            <div class="kpi-label">PIPELINE TIER</div>
            <div class="kpi-val" style="font-size: 14px; color: #38bdf8;">PHASE 5.5 CONSENSUS</div>
            <div class="kpi-note">Quad-Layer Detection</div>
        </div>
        """,
            unsafe_allow_html=True,
        )

    # Cryptographic Hash Seal
    sha = safe_str(getattr(bundle, "evidence_sha256", "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"))
    st.markdown(
        f"""
    <div class="soc-panel" style="background: #090e18; border: 1px solid #1e293b; padding: 10px 14px; margin-top: 10px; margin-bottom: 14px;">
        <div style="display: flex; justify-content: space-between; align-items: center; font-family: monospace; font-size: 11px;">
            <span><strong>CRYPTOGRAPHIC INTEGRITY:</strong> <span style="color: #38bdf8;">{sha}</span></span>
            <span class="badge badge-online">VERIFIED SHA-256</span>
        </div>
    </div>
    """,
        unsafe_allow_html=True,
    )

    # FORENSIC EVIDENCE BUNDLE PAYLOAD JSON Display
    st.markdown("<div class='soc-panel-title'>FORENSIC EVIDENCE BUNDLE PAYLOAD JSON</div>", unsafe_allow_html=True)

    try:
        if hasattr(bundle, "to_dict"):
            payload_dict = bundle.to_dict()
        else:
            payload_dict = asdict(bundle)
    except Exception:
        payload_dict = {
            "event_id": bundle.event_id,
            "timestamp_utc": bundle.timestamp_utc,
            "location": bundle.location,
            "security_features": bundle.security_features,
            "physical_rules": bundle.physical_rules,
            "isolation_forest": bundle.isolation_forest,
            "xgboost": bundle.xgboost,
            "temporal_model": bundle.temporal_model,
            "data_quality": bundle.data_quality
        }

    payload_json = json.dumps(payload_dict, indent=2)

    # Copy JSON / Download Button
    btn_col1, btn_col2 = st.columns([2, 5])
    with btn_col1:
        st.download_button(
            label="COPY / EXPORT JSON PAYLOAD",
            data=payload_json,
            file_name=f"evidence_bundle_{selected_event_id}.json",
            mime="application/json",
            key=f"btn_dl_json_{selected_event_id}"
        )

    st.code(payload_json, language="json")
